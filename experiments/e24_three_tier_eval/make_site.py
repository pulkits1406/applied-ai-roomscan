"""PSEUDO-GT benchmark site from the LiDAR v1.1 plan of single_scan_with_ceiling.

References = our own LiDAR reconstruction (not a laser). Scored captures are independent inputs
only: the two other LiDAR captures of the apartment, the simulated photo folders, and the
walkthrough video; the with_ceiling LiDAR capture itself is not scored against itself. Rooms with
inferred walls in the reference are excluded (a reference wall must be observed).

    uv run roomscan-lidar single_scan_with_ceiling runs/e24/lidar_v11
    uv run python experiments/e24_three_tier_eval/make_site.py runs/e24/lidar_v11/plan.json
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "benchmark/pseudo_gt_lidar_v11"
CAPTURES = [
    {"id": "lidar_floor_only", "tier": "lidar", "path": "single_scan_floor_only", "app": "Stray Scanner",
     "note": "independent LiDAR capture without upper-wall sweep"},
    {"id": "lidar_single_room", "tier": "lidar", "path": "single_room", "app": "Stray Scanner", "note": "partial LiDAR capture"},
    {"id": "photo_diverse_k6", "tier": "photo", "path": "cache/photo_sim/single_scan_with_ceiling_K6",
     "note": "simulated: 6 view-diverse low-overlap stills per room (e23)"},
    {"id": "photo_sweep_k8", "tier": "photo", "path": "cache/photo_sim/single_scan_with_ceiling_K8_sweep",
     "note": "simulated: up to 8 overlapping stills per room (e23)"},
    {"id": "video_with_ceiling", "tier": "video", "path": "single_scan_with_ceiling/rgb.mp4", "app": "plain video (Stray rgb.mp4)",
     "note": "RGB only; same walk as the reference, so not independent of its trajectory"},
]


def main(plan_path="runs/e24/lidar_v11/plan.json"):
    plan = json.loads((ROOT / plan_path).read_text())
    S = {s["id"]: s for s in plan["surfaces"]}
    rooms, excluded = [], []
    for r in plan["rooms"]:
        walls = [S[w] for w in r["wall_ids"]]
        if any(w["length"]["status"] != "measured" for w in walls):
            excluded.append(r["id"]); continue
        widx = {w: f"W{k + 1}" for k, w in enumerate(r["wall_ids"])}
        g = {"id": r["id"], "walls": [{"id": widx[w], "length_m": round(S[w]["length"]["value"], 4)} for w in r["wall_ids"]],
             "floor_area_m2": round(r["floor_area"]["value"], 4)}
        if r["ceiling_height"]["value"] is not None:
            g["ceiling_height_m"] = [round(r["ceiling_height"]["value"], 4)]
        ops = []
        for o in plan["openings"]:
            if r["id"] in o["room_ids"] and o["wall_id"] in widx and o["width"]["status"] == "measured":
                other = [x for x in o["room_ids"] if x != r["id"]][0]
                ops.append({"id": o["id"], "kind": "doorway", "wall": widx[o["wall_id"]], "width_m": round(o["width"]["value"], 4), "connects": other})
        if ops:
            g["openings"] = ops
        rooms.append(g)
    site = {"site_id": "pseudo_gt_lidar_v11", "gt_kind": "pseudo_lidar", "purpose": "pseudo",
            "instrument": f"NONE - references are our LiDAR v1.1 plan ({plan_path}) of single_scan_with_ceiling; excluded rooms with inferred walls: {excluded}",
            "rooms": rooms, "captures": [{k: v for k, v in c.items() if k != "note"} for c in CAPTURES]}
    SITE.mkdir(parents=True, exist_ok=True)
    hdr = "# PSEUDO-GT: generated by experiments/e24_three_tier_eval/make_site.py - not a laser benchmark.\n" + \
          "".join(f"# {c['id']}: {c['note']}\n" for c in CAPTURES)
    (SITE / "site.yaml").write_text(hdr + yaml.safe_dump(site, sort_keys=False))
    print(f"{len(rooms)} rooms, excluded {excluded}")


if __name__ == "__main__":
    main(*sys.argv[1:])
