"""Exercise the benchmark harness on the supplied captures (PSEUDO-GT only).

Builds the with_ceiling LiDAR plan from each room's longest visit (visit0) and second visit
(visit1). visit0's plan is written as a pseudo-GT site (gt_kind: pseudo_lidar); both plans are
scored with the same repeat_group. visit0 vs its own pseudo-GT is trivially exact; the
informative numbers are visit1's errors and the repeatability rows.
"""
from pathlib import Path
import yaml
from roomscan.lidar_pipeline import build_plan
from roomscan.bench.evaluate import run

ROOT = Path(__file__).resolve().parents[2]
CAP = ROOT / "single_scan_with_ceiling"
SITE = ROOT / "benchmark/pseudo_gt_stray_apartment"; RUN = ROOT / "runs/pseudo_v0"
plans = {f"visit{k}": build_plan(CAP, visit_rank=k)[0] for k in (0, 1)}
for k, p in plans.items():
    (RUN / k).mkdir(parents=True, exist_ok=True); (RUN / k / "plan.json").write_text(p.model_dump_json(indent=1))
g = plans["visit0"]; surf = {s.id: s for s in g.surfaces}
rooms = []
common = {r.id for r in plans["visit0"].rooms} & {r.id for r in plans["visit1"].rooms}
for r in g.rooms:
    if r.id not in common: continue
    rooms.append({"id": r.id, "walls": [{"id": f"W{i+1}", "length_m": round(surf[w].length.value, 4)} for i, w in enumerate(r.wall_ids)],
                  **({"ceiling_height_m": [round(r.ceiling_height.value, 4)]} if r.ceiling_height.value else {}),
                  "floor_area_m2": round(r.floor_area.value, 3)})
ident = {r["id"]: r["id"] for r in rooms}
site = {"site_id": "pseudo_gt_stray_apartment", "gt_kind": "pseudo_lidar", "purpose": "pseudo",
        "instrument": "NONE - references are our own LiDAR v0 reconstruction (visit0) of single_scan_with_ceiling",
        "rooms": rooms,
        "captures": [{"id": k, "tier": "lidar", "path": "single_scan_with_ceiling", "rooms": list(ident), "repeat_group": "with_ceiling_visits", "room_map": ident} for k in plans]}
SITE.mkdir(parents=True, exist_ok=True); (SITE / "site.yaml").write_text("# PSEUDO-GT: generated by experiments/e15_harness_on_samples/make_pseudo_site.py\n" + yaml.safe_dump(site, sort_keys=False))
rep = run(str(SITE), str(RUN))
print((RUN / "eval" / "pseudo_gt_stray_apartment.md").read_text())
v1 = next(c for c in rep["captures"] if c["capture"] == "visit1")
import numpy as np
errs = [abs(w["abs_err"]) for w in v1["walls"] if w.get("pred") is not None]
print("visit1 wall |err| vs pseudo-GT: median %.1f mm, p90 %.1f mm, n=%d" % (1000 * np.median(errs), 1000 * np.percentile(errs, 90), len(errs)))
